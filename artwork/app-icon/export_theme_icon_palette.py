"""Export the finite launcher palette from the shared BiliPai vector source (no Gradle)."""
from pathlib import Path
import xml.etree.ElementTree as ET
import json

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / 'app/src/main/res'
JAVA = ROOT / 'app/src/main/java/com/android/purebilibili'
SVG = '{http://www.w3.org/2000/svg}'
source = ET.parse(Path(__file__).with_name('bilipai-mark.svg')).getroot()
path, = source.findall(f'{SVG}path')
assert path.attrib['fill-rule'] == 'evenodd'
styles, colors, activities, aliases, classes, icons, themes = [], [], [], [], [], [], []
palette = json.loads(Path(__file__).with_name('bilipai-icon-color-palette.json').read_text())
foregrounds, backgrounds = palette['foreground'], palette['background']
for index in range(216 + len(foregrounds) * len(backgrounds)):
    if index < 216:
        r, g, b = index // 36 * 51, index // 6 % 6 * 51, index % 6 * 51
        hex_color = f'#{r:02X}{g:02X}{b:02X}'
    else:
        hex_color = foregrounds[(index - 216) % len(foregrounds)]
        r, g, b = [int(hex_color[i:i+2], 16) for i in (1, 3, 5)]
    linear = lambda c: c / 255 / 12.92 if c / 255 <= .04045 else ((c / 255 + .055) / 1.055) ** 2.4
    luminance = .2126 * linear(r) + .7152 * linear(g) + .0722 * linear(b)
    background = ('#242321' if luminance > .4 else '#FFFFFF') if index < 216 else backgrounds[(index - 216) // len(foregrounds)]
    tag = f'{index:03d}'
    name = f'ic_bilipai_theme_{tag}'
    (RES / f'drawable/{name}.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="1254" android:viewportHeight="1254">
    <path android:fillType="evenOdd" android:fillColor="{hex_color}" android:pathData="{path.attrib['d']}" />
</vector>
''')
    (RES / f'mipmap-anydpi-v26/{name}.xml').write_text(f'''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/bilipai_theme_background_{tag}" />
    <foreground android:drawable="@drawable/{name}" />
    <monochrome android:drawable="@drawable/ic_bilipai_mark_monochrome" />
</adaptive-icon>
''')
    colors.append(f'    <color name="bilipai_theme_background_{tag}">{background}</color>')
    styles.append(f'''    <style name="Theme.PureBiliBili.Splash.BiliPaiTheme{tag}" parent="Theme.PureBiliBili">
        <item name="windowSplashScreenBackground">@color/bilipai_theme_background_{tag}</item>
        <item name="windowSplashScreenAnimatedIcon">@mipmap/{name}</item>
    </style>''')
    activities.append(f'''        <activity android:name=".MainActivitySplashBiliPaiTheme{tag}"
            android:exported="false" android:enabled="true"
            android:icon="@mipmap/{name}" android:roundIcon="@mipmap/{name}"
            android:theme="@style/Theme.PureBiliBili.Splash.BiliPaiTheme{tag}" />''')
    for no_icon in [False, True]:
        suffix = 'NoIcon' if no_icon else ''
        target = '.MainActivitySplashNoIcon' if no_icon else f'.MainActivitySplashBiliPaiTheme{tag}'
        aliases.append(f'''        <activity-alias android:name=".MainActivityAliasBiliPaiTheme{tag}{suffix}"
            android:enabled="false" android:exported="true" android:label="@string/app_name"
            android:icon="@mipmap/{name}" android:roundIcon="@mipmap/{name}"
            android:targetActivity="{target}">
            <intent-filter><action android:name="android.intent.action.MAIN" /><category android:name="android.intent.category.LAUNCHER" /></intent-filter>
            <meta-data android:name="android.app.shortcuts" android:resource="@xml/shortcuts" />
        </activity-alias>''')
    classes.append(f'class MainActivitySplashBiliPaiTheme{tag} : MainActivityLauncherEntry()')
    icons.append(f'    R.mipmap.{name},')
    themes.append(f'    R.style.Theme_PureBiliBili_Splash_BiliPaiTheme{tag},')
(RES / 'values/bilipai_theme_icon_palette.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'+'\n'.join(colors+styles)+'\n</resources>\n')
(JAVA / 'BiliPaiThemeIconResources.kt').write_text('''// Generated by artwork/app-icon/export_theme_icon_palette.py.
package com.android.purebilibili

internal val biliPaiThemeIconResources = intArrayOf(
'''+ '\n'.join(icons)+'''
)
internal val biliPaiThemeSplashThemes = intArrayOf(
'''+ '\n'.join(themes)+'''
)
'''+ '\n'.join(classes)+'\n')
p = ROOT / 'app/src/main/AndroidManifest.xml'
s = p.read_text()
start_marker = '        <!-- BEGIN BILIPAI THEME ICON PALETTE -->'
end_marker = '        <!-- END BILIPAI THEME ICON PALETTE -->'
if start_marker in s:
    start = s.index(start_marker); end = s.index(end_marker, start)+len(end_marker)
    s = s[:start]+s[end:].lstrip("\n")
block = start_marker+'\n'+'\n\n'.join(activities+aliases)+'\n'+end_marker+'\n'
s = s.replace('    </application>', block+'    </application>')
p.write_text(s)

choices_path = JAVA / 'core/store/BiliPaiIconColorChoices.kt'
choice_source = '// Generated by artwork/app-icon/export_theme_icon_palette.py.\npackage com.android.purebilibili.core.store\n\n'
choice_source += f'const val BILIPAI_THEME_ICON_PALETTE_SIZE = {216 + len(foregrounds) * len(backgrounds)}\n\n'
for name, values in [('biliPaiIconForegroundChoices', foregrounds), ('biliPaiIconBackgroundChoices', backgrounds)]:
    choice_source += 'val ' + name + ': List<Int> = listOf(\n' + ''.join('    0xFF' + value[1:] + '.toInt(),\n' for value in values) + ')\n\n'
choices_path.write_text(choice_source)
